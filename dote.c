const char* color(int x) {
    switch (x) {
        case 0: return "\x1b[48;5;223m  \x1b[0m"; // 肌
        case 1: return "\x1b[48;5;196m  \x1b[0m"; // 赤
        case 2: return "\x1b[48;5;94m  \x1b[0m";  // 茶
        case 3: return "\x1b[48;5;226m  \x1b[0m"; // 黄
        case 4: return "\x1b[48;5;208m  \x1b[0m"; // 橙
        case 5: return "\x1b[48;5;0m  \x1b[0m";   // 黒
        case 6: return "\x1b[48;5;229m  \x1b[0m"; // クリーム
        case 7: return "\x1b[48;5;0m  \x1b[0m";   // 背景黒
        case 8: return "\x1b[48;5;15m  \x1b[0m";  // 白
        default: return "\x1b[0m  ";
    }
}

void dote(int k) {
    printf("\e[H\e[J\e[?7l");         
    for (int i = 0; i < 14; i++) {
        printf("%*s", k, "");          
        for (int j = 0; j < 17; j++) {
            int x = (k % 2 == 1) ? b[i][j] : a[i][j];
            printf("%s", color(x));  
        }
        printf("\n");
    }
    fflush(stdout);
    usleep(125000);
}

int main(void) {
    for (int k = 0; k < 56; k++) dote(k);
    for (int k = 55; k >= 0; --k) dote(k);
    printf("\e[?7h");
    return 0;
}
